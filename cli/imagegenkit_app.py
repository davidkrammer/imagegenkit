    ap.add_argument("--port", type=int, default=0)
    ap.add_argument("--no-window", action="store_true")
    ap.add_argument("--stay", action="store_true", help="keep running when no window is open")
    a = ap.parse_args()
    main(port=a.port, open_window=not a.no_window, stay=a.stay)
