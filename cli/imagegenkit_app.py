"""ImageGenKit app for Windows (and Linux): a small local web app on top of the imagegenkit command.

    imagegenkit app            open the app (an Edge or Chrome app window, else a browser tab)
    imagegenkit app --no-window

The server listens on 127.0.0.1 only. Every API call needs the per-launch token that is put into the page, and the
Host header must be the loopback address, so other websites can't drive it. Images are generated by running the
imagegenkit command in a subprocess, exactly as an agent would, so the log, limits and settings are shared.
Stdlib only.
"""
