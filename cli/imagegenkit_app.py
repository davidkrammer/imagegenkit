# ---------- helpers ----------

def python_exe():
    """A console-less python for subprocesses when we are pythonw, else this interpreter."""
    exe = Path(sys.executable)
    if exe.name.lower() == "pythonw.exe" and (exe.parent / "python.exe").exists():
        return str(exe.parent / "python.exe")
    return sys.executable


def run_cli(args, input_text=None, timeout=300):
    """Run imagegenkit with args; returns (code, stdout, stderr)."""
    env = dict(os.environ, IMAGEGENKIT_NO_UPDATE="1", PYTHONIOENCODING="utf-8")
    try:
        r = subprocess.run([python_exe(), CLI] + args, input=input_text, capture_output=True, encoding="utf-8",
                           errors="replace", timeout=timeout, env=env, stdin=None if input_text is not None else subprocess.DEVNULL,
                           creationflags=NO_WINDOW)
    except subprocess.TimeoutExpired:
        return 124, "", "timed out"
    except OSError as e:
        return 1, "", str(e)
    return r.returncode, r.stdout, r.stderr


def cli_json(args, timeout=300):
    code, out, err = run_cli(args, timeout=timeout)
    try:
        return json.loads(out), err
    except ValueError:
        raise ApiFailure(clean_err(err) or f"imagegenkit {' '.join(args[:2])} failed")


def clean_err(err):
    lines = [ln.strip() for ln in (err or "").splitlines() if ln.strip()]
    return "\n".join(ln.replace("imagegenkit: ", "", 1) for ln in lines[-6:])


class ApiFailure(Exception):
    pass


def read_log(limit=None):
    entries = []
    try:
        with igk.LOG_FILE.open(encoding="utf-8") as f:
            for i, line in enumerate(f):
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                if isinstance(e, dict):
                    e["_id"] = i
                    entries.append(e)
    except OSError:
        pass
    entries.reverse()
    return entries[:limit] if limit else entries


_ALLOWED = {"key": None, "paths": set()}


def allowed_files():
    """Image files the app may show: everything in the log (outputs, refs, thumbs). Cached per log size/mtime."""
    try:
        st = igk.LOG_FILE.stat()
        key = (st.st_size, st.st_mtime_ns)
    except OSError:
        key = None
    if key != _ALLOWED["key"]:
        paths = set()
        for e in read_log():
            for k in ("outputs", "refs", "thumbs"):
                for p in e.get(k) or []:
                    if p:
                        paths.add(os.path.normcase(os.path.abspath(p)))
        _ALLOWED.update(key=key, paths=paths)
    return _ALLOWED["paths"]


def is_allowed(path):
    p = os.path.normcase(os.path.abspath(path))
    if Path(p).suffix.lower() not in IMAGE_EXT:
        return False
    for root in (UPLOADS, igk.THUMB_DIR):
        r = os.path.normcase(os.path.abspath(root))
        if p.startswith(r + os.sep):
            return True
    return p in allowed_files()


def provider_rows(cfg):
    rows = []
    cat = {e["id"]: e for e in igk.catalog_providers()}
    try:
        repo_cat = json.loads((HERE.parent / "catalog" / "providers.json").read_text(encoding="utf-8"))["providers"]
    except (OSError, ValueError, KeyError):
        try:
            repo_cat = json.loads((HERE / "providers.json").read_text(encoding="utf-8"))["providers"]
        except (OSError, ValueError, KeyError):
            repo_cat = []
    for e in repo_cat:
        cat.setdefault(e["id"], e)
    for name, spec in igk.all_providers(cfg).items():
        ready, why = igk.readiness(spec)
        c = dict(cat.get(spec.get("catalog") or name) or {})
        if not igk.IS_MAC and c.get("tagline"):  # the shared catalog is written for the Mac app
            c["tagline"] = c["tagline"].replace("your Mac", "your PC").replace("this Mac", "this PC")
        rows.append({"name": name, "label": spec["label"], "type": spec["type"], "builtin": spec["builtin"],
                     "needs_key": spec["type"] not in igk.KEYLESS_TYPES, "ready": ready, "status": why,
                     "base_url": spec.get("base_url"), "model": igk.pref(cfg, spec, "model") or spec.get("model"),
                     "key_url": spec.get("key_url") or c.get("key_url"), "tagline": c.get("tagline"),
                     "price_hint": c.get("price_hint"), "steps": c.get("steps") or [], "models": c.get("models") or [],
                     "transparent": spec["type"] in igk.CAN_TRANSPARENT, "tested": c.get("tested"),
                     "edits": spec.get("edits", True) is not False, "env": spec.get("env"),
                     "defaults": (cfg.get("provider_defaults") or {}).get(name) or {}})
    # catalog providers not added yet (OpenAI-compatible ones are added through the catalog list automatically)
    return rows


def agent_targets():
    out = []
    for key, home in (("claude", Path.home() / ".claude"), ("codex", Path.home() / ".codex")):
        skill = home / "skills" / "imagegenkit" / "SKILL.md"
        version = None
        if skill.exists():
            try:
                import re
                m = re.search(r"version:\s*([\w.\-]+)", skill.read_text(encoding="utf-8", errors="ignore"))
                version = m.group(1) if m else "?"
            except OSError:
                version = "?"
        out.append({"id": key, "label": "Claude Code" if key == "claude" else "Codex", "present": home.is_dir(),
                    "installed": skill.exists(), "version": version, "path": str(skill)})
    return out


def skill_source():
    for p in (HERE / "SKILL.md", HERE.parent / "skill" / "SKILL.md"):
        if p.exists():
            return p
    return None


def state():
    cfg = igk.load_config()
    cost, images, runs = igk.month_usage(cfg)
    cost_limit, image_limit, stop = igk.limit_values(cfg)
    user = igk.read_user_config()
    return {
        "version": igk.VERSION, "platform": sys.platform, "device": igk.DEVICE, "key_store": igk.KEY_STORE,
        "homepage": igk.HOMEPAGE, "providers": provider_rows(cfg),
        "order": cfg.get("order") or [], "tasks": cfg.get("tasks") or {}, "task_info": igk.TASKS,
        "output_dir": str(Path(str(cfg.get("output_dir") or igk.DEFAULTS["output_dir"])).expanduser()),
        "config": {k: v for k, v in cfg.items() if not k.startswith("_")}, "user_config": user,
        "usage": {"month": time.strftime("%Y-%m"), "cost": round(cost, 4), "images": images, "runs": runs},
        "limits": {"monthly_cost": cost_limit, "monthly_images": image_limit, "stop_paid": stop},
        "agents": agent_targets(), "local_backend": igk.local_backend(cfg),
        "auto_update": cfg.get("auto_update") is not False,
    }


def log_payload(limit):
    cfg = igk.load_config()
    out = []
    for e in read_log(limit):
        e = dict(e)
        e["cost"] = round(igk.estimate_cost(e, cfg), 4)
        e["exists"] = [bool(p) and os.path.exists(p) for p in e.get("outputs") or []]
        out.append(e)
    return out


# ---------- jobs (generate, model downloads) ----------

class Job:
    def __init__(self, kind, args, label, stdin_text=None):
        self.id = uuid.uuid4().hex[:12]
        self.kind, self.args, self.label, self.stdin_text = kind, args, label, stdin_text
        self.lines, self.outputs, self.events = [], [], []
        self.status, self.code, self.started, self.ended = "running", None, time.time(), None
        self.proc = None

    def run(self):
        env = dict(os.environ, IMAGEGENKIT_NO_UPDATE="1", PYTHONIOENCODING="utf-8", PYTHONUNBUFFERED="1")
        try:
            self.proc = subprocess.Popen([python_exe(), CLI] + self.args, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                         stdin=subprocess.PIPE if self.stdin_text is not None else subprocess.DEVNULL,
                                         env=env, creationflags=NO_WINDOW)
            if self.stdin_text is not None:  # the prompt: never on the command line (it could start with "-")
                self.proc.stdin.write(self.stdin_text.encode("utf-8"))
                self.proc.stdin.close()
        except OSError as e:
            self.lines.append(str(e))
            self.status, self.code, self.ended = "failed", 1, time.time()
            return

        def read_err():
            for raw in iter(self.proc.stderr.readline, b""):
                text = raw.decode("utf-8", "replace").rstrip("\r\n")
                for part in text.split("\r"):
                    part = part.strip()
                    if part:
                        self.lines.append(part.replace("imagegenkit: ", "", 1))
                        del self.lines[:-200]

        t = threading.Thread(target=read_err, daemon=True)
        t.start()
        for raw in iter(self.proc.stdout.readline, b""):
            text = raw.decode("utf-8", "replace").strip()
            if not text:
                continue
            if text.startswith("{"):
                try:
                    self.events.append(json.loads(text))
                    del self.events[:-50]
                    continue
                except ValueError:
                    pass
            self.outputs.append(text)
        self.code = self.proc.wait()
        t.join(timeout=2)
        self.ended = time.time()
        if self.status != "cancelled":
            self.status = "done" if self.code == 0 else "failed"

    def cancel(self):
        if self.proc and self.proc.poll() is None:
            self.status = "cancelled"
            self.proc.terminate()

    def view(self):
        return {"id": self.id, "kind": self.kind, "label": self.label, "status": self.status, "code": self.code,
                "lines": self.lines[-40:], "outputs": self.outputs, "event": self.events[-1] if self.events else None,
                "seconds": round((self.ended or time.time()) - self.started, 1)}


def start_job(kind, args, label, stdin_text=None):
    job = Job(kind, args, label, stdin_text)
    with JOBS_LOCK:
        JOBS[job.id] = job
        for old in [j for j in JOBS.values() if j.ended and time.time() - j.ended > 3600]:
            JOBS.pop(old.id, None)
    threading.Thread(target=job.run, daemon=True).start()
    return job


def generate_args(b):
    target = b.get("target") or "draft"
    if target not in igk.TASKS and target not in igk.all_providers(igk.load_config()):
        raise ApiFailure(f"unknown task or provider {target}")
    prompt = (b.get("prompt") or "").strip()
    if not prompt:
        raise ApiFailure("Write a prompt first.")
    args = [target, "-"]  # "-": the prompt comes on stdin
    for key, flag in (("aspect", "--aspect"), ("resolution", "--resolution"), ("quality", "--quality"),
                      ("background", "--background"), ("format", "--format"), ("model", "-m"), ("size", "--size")):
        v = b.get(key)
        if v not in (None, "", "auto" if key in ("aspect",) else None):
            args += [flag, str(v)]
    n = int(b.get("n") or 1)
    if n > 1:
        args += ["-n", str(min(n, 8))]
    for r in b.get("refs") or []:
        if not is_allowed(r) or not os.path.isfile(r):
            raise ApiFailure(f"reference image not found: {r}")
        args += ["-i", r]
    if b.get("provider") and target in igk.TASKS:
        args += ["-p", b["provider"]]
    if b.get("out"):
        args += ["-o", b["out"]]
    for i in range(3, len(args), 2):  # option values from the page are never options themselves
        if str(args[i]).startswith("-"):
            raise ApiFailure(f"{args[i - 1]} can't start with '-'")
    return args, target, prompt


# ---------- system actions ----------

def reveal(path):
    if sys.platform == "win32":
        subprocess.Popen(["explorer", f"/select,{os.path.normpath(path)}"])
    elif sys.platform == "darwin":
        subprocess.Popen(["open", "-R", path])
    else:
        subprocess.Popen(["xdg-open", str(Path(path).parent)])


def open_path(path):
    if sys.platform == "win32":
        os.startfile(path)  # noqa: S606 (a file from the log or a folder the user set)
    elif sys.platform == "darwin":
        subprocess.Popen(["open", path])
    else:
        subprocess.Popen(["xdg-open", path])


TERMINAL_COMMANDS = {
    "install-codex": "npm install -g @openai/codex",
    "login-codex": "codex login",
    "install-grok": "irm https://x.ai/cli/install.ps1 | iex",
    "login-grok": "grok login",
}


def open_terminal(action):
    """Runs a setup command in a new terminal window the user can see and answer."""
    cmd = TERMINAL_COMMANDS.get(action)
    if not cmd:
        raise ApiFailure("unknown action")
    if sys.platform == "win32":
        wt = shutil.which("wt")
        ps = ["powershell", "-NoExit", "-NoProfile", "-Command", f"Write-Host '> {cmd}'; {cmd}"]
        subprocess.Popen(([wt, "new-tab"] + ps) if wt else ps, creationflags=getattr(subprocess, "CREATE_NEW_CONSOLE", 0))
    elif sys.platform == "darwin":
        subprocess.Popen(["osascript", "-e", f'tell app "Terminal" to do script "{cmd}"'])
    else:
        term = shutil.which("x-terminal-emulator") or shutil.which("gnome-terminal")
        if not term:
            raise ApiFailure(f"open a terminal and run: {cmd}")
        subprocess.Popen([term, "--", "sh", "-c", f"{cmd}; exec $SHELL"])
    return cmd


def install_skill(target):
    src = skill_source()
    if not src:
        raise ApiFailure("SKILL.md isn't installed next to the app (reinstall ImageGenKit)")
    home = {"claude": Path.home() / ".claude", "codex": Path.home() / ".codex"}.get(target)
    if not home:
        raise ApiFailure("unknown agent")
    dest = home / "skills" / "imagegenkit" / "SKILL.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dest)
    return str(dest)


def remove_skill(target):
    home = {"claude": Path.home() / ".claude", "codex": Path.home() / ".codex"}.get(target)
    dest = home / "skills" / "imagegenkit" / "SKILL.md" if home else None
    if dest and dest.exists():
        dest.unlink()
        try:
            dest.parent.rmdir()
        except OSError:
            pass


def apply_config(changes):
    """changes: {"set": {"dotted.key": value}, "unset": ["dotted.key"]}."""
    data = igk.read_user_config()
    for k, v in (changes.get("set") or {}).items():
        igk.set_dotted(data, k, v)
    for k in changes.get("unset") or []:
        igk.set_dotted(data, k, None)
    igk.write_user_config(data)


# ---------- http ----------

class Handler(BaseHTTPRequestHandler):
    server_version = "ImageGenKit"

    def log_message(self, fmt, *a):
        if os.environ.get("IMAGEGENKIT_DEBUG"):
            sys.stderr.write("%s\n" % (fmt % a))

    # -- plumbing --
    def host_ok(self):
        host = (self.headers.get("Host") or "").split(":")[0]
        return host in ("127.0.0.1", "localhost")

    def token_ok(self):
        return secrets.compare_digest(self.headers.get("X-IGK-Token") or "", TOKEN)

    def send_json(self, data, status=200):
        raw = json.dumps(data, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(raw)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(raw)

    def send_bytes(self, data, ctype, cache=False, headers=None):
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "private, max-age=3600" if cache else "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(data)

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        if n > 64 * 1024 * 1024:
            raise ApiFailure("too large")
        return self.rfile.read(n) if n else b""

    def json_body(self):
        raw = self.body()
        try:
            return json.loads(raw or b"{}")
        except ValueError:
            raise ApiFailure("bad JSON")

    def deny(self, status=403):
        self.send_response(status)
        self.send_header("Content-Length", "0")
        self.end_headers()

    # -- routes --
    def do_GET(self):
        if not self.host_ok():
            return self.deny()
        url = urllib.parse.urlparse(self.path)
        q = urllib.parse.parse_qs(url.query)
        path = url.path
        if path in ("/", "/index.html"):
            if q.get("t", [""])[0] != TOKEN:
                return self.deny()
            nonce = secrets.token_urlsafe(12)
            html = (STATIC / "index.html").read_text(encoding="utf-8").replace("__IGK_TOKEN__", TOKEN)
            html = html.replace("<script>", f'<script nonce="{nonce}">')
            csp = (f"default-src 'none'; script-src 'self' 'nonce-{nonce}'; style-src 'self' 'unsafe-inline'; "
                   "img-src 'self' data: blob:; connect-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'; "
                   "frame-ancestors 'none'")
            return self.send_bytes(html.encode("utf-8"), "text/html; charset=utf-8", headers={"Content-Security-Policy": csp})
        if path.startswith("/static/"):
            f = (STATIC / path[len("/static/"):]).resolve()
            if STATIC.resolve() not in f.parents or not f.is_file():
                return self.deny(404)
            ctype = mimetypes.guess_type(f.name)[0] or "application/octet-stream"
            if f.suffix == ".js":
                ctype = "text/javascript; charset=utf-8"
            return self.send_bytes(f.read_bytes(), ctype)
        if path == "/file":  # <img src> can't send headers: the token comes as a query parameter
            if q.get("t", [""])[0] != TOKEN:
                return self.deny()
            p = q.get("path", [""])[0]
            if not p or not is_allowed(p) or not os.path.isfile(p):
                return self.deny(404)
            ctype = mimetypes.guess_type(p)[0] or "application/octet-stream"
            return self.send_bytes(Path(p).read_bytes(), ctype, cache=True)
        if not path.startswith("/api/") or not self.token_ok():
            return self.deny()
        LAST_PING[0] = time.time()
        try:
            if path == "/api/ping":
                return self.send_json({"ok": True, "version": igk.VERSION})
            if path == "/api/state":
                return self.send_json(state())
            if path == "/api/log":
                return self.send_json(log_payload(int(q.get("limit", ["0"])[0] or 0) or None))
            if path.startswith("/api/jobs/"):
                job = JOBS.get(path.rsplit("/", 1)[-1])
                return self.send_json(job.view()) if job else self.send_json({"error": "no such job"}, 404)
            if path == "/api/jobs":
                return self.send_json([j.view() for j in JOBS.values() if j.status == "running"])
            if path == "/api/local":
                data, _ = cli_json(["local-models", "list", "--json"] + (["--refresh"] if q.get("refresh") else []), timeout=60)
                return self.send_json(data)
            if path == "/api/local/search":
                data, _ = cli_json(["local-models", "search", "--json", "--limit", "20", "--", q.get("q", [""])[0]], timeout=120)
                return self.send_json(data)
            if path == "/api/models":
                code, out, err = run_cli(["models", "--", q.get("provider", ["openai"])[0]], timeout=60)
                if code:
                    raise ApiFailure(clean_err(err))
                return self.send_json([ln.strip() for ln in out.splitlines() if ln.strip()])
        except ApiFailure as e:
            return self.send_json({"error": str(e)}, 400)
        except Exception as e:  # keep the app alive
            return self.send_json({"error": f"{type(e).__name__}: {e}"}, 500)
        return self.deny(404)

    def do_POST(self):
        if not self.host_ok() or not self.token_ok():
            return self.deny()
        LAST_PING[0] = time.time()
        path = urllib.parse.urlparse(self.path).path
        try:
            if path == "/api/upload":
                name = urllib.parse.unquote(self.headers.get("X-Filename") or "image.png")
                ext = Path(name).suffix.lower()
                if ext not in IMAGE_EXT:
                    raise ApiFailure("only images can be used as references")
                data = self.body()
                if not data:
                    raise ApiFailure("empty file")
                UPLOADS.mkdir(parents=True, exist_ok=True)
                dest = UPLOADS / f"{time.strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:6]}{ext}"
                dest.write_bytes(data)
                return self.send_json({"path": str(dest)})
            b = self.json_body()
            if path == "/api/generate":
                args, target, prompt = generate_args(b)
                job = start_job("generate", args, f"{target}: {prompt[:60]}", stdin_text=prompt)
                return self.send_json(job.view())
            if path.startswith("/api/jobs/") and path.endswith("/cancel"):
                job = JOBS.get(path.split("/")[3])
                if job:
                    job.cancel()
                return self.send_json({"ok": True})
            if path == "/api/key":
                provider, key = b.get("provider", ""), (b.get("key") or "").strip()
                if not provider or not key:
                    raise ApiFailure("provider and key are needed")
                code, out, err = run_cli(["set-key", "--stdin", "--", provider], input_text=key, timeout=90)
                if code:
                    raise ApiFailure(clean_err(err) or "couldn't save the key")
                return self.send_json({"ok": True, "message": out.strip()})
            if path == "/api/key/delete":
                code, out, err = run_cli(["delete-key", "--", b.get("provider", "")])
                return self.send_json({"ok": code == 0, "message": (out or err).strip()})
            if path == "/api/check":
                args = ["check", "--json"] + (["--", b["provider"]] if b.get("provider") else [])
                code, out, err = run_cli(args, timeout=120)
                try:
                    return self.send_json(json.loads(out))
                except ValueError:
                    raise ApiFailure(clean_err(err) or "check failed")
            if path == "/api/config":
                apply_config(b)
                return self.send_json(state())
            if path == "/api/provider":
                if b.get("action") == "add":
                    args = ["provider", "--base-url", b.get("base_url", ""), "--model", b.get("model", "")]
                    if b.get("label"):
                        args += ["--label", b["label"]]
                    if b.get("edit_model"):
                        args += ["--edit-model", b["edit_model"]]
                    if any(str(v).startswith("-") for v in args[2::2]):
                        raise ApiFailure("values can't start with '-'")
                    args += ["--", "add", b.get("name", "")]
                else:
                    args = ["provider", "--", "remove", b.get("name", "")]
                code, out, err = run_cli(args)
                if code:
                    raise ApiFailure(clean_err(err))
                return self.send_json({"ok": True, "message": out.strip()})
            if path == "/api/local/add":
                args = ["local-models", "add", "--json"]
                if b.get("recipe"):
                    args += ["--recipe", b["recipe"]]
                if b.get("file"):
                    args += ["--file", b["file"]]
                if any(str(v).startswith("-") for v in args[4::2]):
                    raise ApiFailure("values can't start with '-'")
                args += ["--", b.get("model", "")]
                job = start_job("download", args, b.get("label") or b.get("model", ""))
                return self.send_json(job.view())
            if path == "/api/local/remove":
                data, _ = cli_json(["local-models", "remove", "--json", "--", b.get("model", "")])
                return self.send_json(data)
            if path == "/api/reveal":
                p = b.get("path", "")
                if not is_allowed(p) or not os.path.exists(p):
                    raise ApiFailure("file not found")
                reveal(p)
                return self.send_json({"ok": True})
            if path == "/api/open":
                p = b.get("path", "")
                if b.get("folder") == "output":
                    p = state()["output_dir"]
                    Path(p).mkdir(parents=True, exist_ok=True)
                elif not is_allowed(p) or not os.path.exists(p):
                    raise ApiFailure("file not found")
                open_path(p)
                return self.send_json({"ok": True})
            if path == "/api/url":
                u = b.get("url", "")
                if not u.startswith("https://"):
                    raise ApiFailure("only https links")
                webbrowser.open(u)
                return self.send_json({"ok": True})
            if path == "/api/terminal":
                return self.send_json({"ok": True, "command": open_terminal(b.get("action", ""))})
            if path == "/api/skill":
                if b.get("remove"):
                    remove_skill(b.get("agent", ""))
                    return self.send_json({"ok": True})
                return self.send_json({"ok": True, "path": install_skill(b.get("agent", ""))})
            if path == "/api/update":
                code, out, err = run_cli(["update"], timeout=120)
                return self.send_json({"ok": code == 0, "message": (out.strip() or clean_err(err))})
            if path == "/api/quit":
                self.send_json({"ok": True})
                threading.Thread(target=self.server.shutdown, daemon=True).start()
                return
        except ApiFailure as e:
            return self.send_json({"error": str(e)}, 400)
        except Exception as e:
            return self.send_json({"error": f"{type(e).__name__}: {e}"}, 500)
        return self.deny(404)


