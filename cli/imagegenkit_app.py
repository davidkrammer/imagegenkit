def app_browser():
    """Edge or Chrome, which can open a page as an app window (--app)."""
    if sys.platform == "win32":
        bases = [os.environ.get(k) for k in ("ProgramFiles(x86)", "ProgramFiles", "LOCALAPPDATA")]
        rels = [r"Microsoft\Edge\Application\msedge.exe", r"Google\Chrome\Application\chrome.exe"]
        for rel in rels:
            for base in bases:
                if base and Path(base, rel).exists():
                    return str(Path(base, rel))
        return shutil.which("msedge") or shutil.which("chrome")
    for name in ("google-chrome", "chromium", "chromium-browser", "microsoft-edge"):
        if shutil.which(name):
            return shutil.which(name)
    return None


def launch_window(url):
    exe = app_browser()
    if exe:
        profile = igk.CONFIG_DIR / "app-window"  # its own profile: own window size, no tabs or extensions
        try:
            subprocess.Popen([exe, f"--app={url}", f"--user-data-dir={profile}", "--window-size=1280,860",
                              "--no-first-run", "--no-default-browser-check"], creationflags=NO_WINDOW)
            return
        except OSError:
            pass
    webbrowser.open(url)


def running_instance():
    """(url) of an app server that is already running, so a second launch only opens a window."""
    try:
        info = json.loads(INSTANCE.read_text(encoding="utf-8"))
        req = urllib.request.Request(f"http://127.0.0.1:{info['port']}/api/ping", headers={"X-IGK-Token": info["token"]})
        with urllib.request.urlopen(req, timeout=2) as r:
            if json.loads(r.read()).get("ok"):
                return f"http://127.0.0.1:{info['port']}/?t={info['token']}"
    except (OSError, ValueError, KeyError):
        pass
    return None


def watchdog(server):
    """Quit when no page has talked to the server for a while (the window was closed)."""
    while True:
        time.sleep(5)
        busy = any(j.status == "running" for j in JOBS.values())
        if not busy and time.time() - LAST_PING[0] > IDLE_EXIT:
            server.shutdown()
            return


def main(port=0, open_window=True, cli_path=None, stay=False):
    global CLI
    if cli_path:
        CLI = cli_path
    existing = running_instance() if not port else None
    if existing:
        print(existing, flush=True)
        if open_window:
            launch_window(existing)
        return
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    server.daemon_threads = True
    port = server.server_address[1]
    url = f"http://127.0.0.1:{port}/?t={TOKEN}"
    try:
        igk.CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        INSTANCE.write_text(json.dumps({"port": port, "token": TOKEN, "pid": os.getpid()}), encoding="utf-8")
    except OSError:
        pass
    print(f"ImageGenKit app: {url}", flush=True)
    LAST_PING[0] = time.time() + 30  # give the window time to open
    if open_window:
        launch_window(url)
    if not stay:
        threading.Thread(target=watchdog, args=(server,), daemon=True).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
        try:
            if json.loads(INSTANCE.read_text(encoding="utf-8")).get("pid") == os.getpid():
                INSTANCE.unlink()
        except (OSError, ValueError):
            pass


